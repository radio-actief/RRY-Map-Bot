// The map page's Vue template, compiled ahead of time: the browser then needs no eval to build it
// from the page (the Content-Security-Policy allows none).
// Source: the #app element of index.html. Output: src/map-app.render.js, imported by src/map.js.
// Usage: npm run build:map (after any change inside #app in index.html; a test checks it is current).
//
// Static text marked for translation (data-i18n="key", data-i18n-attr="attr:key; …") becomes
// t('key') in the template, so it renders in the page language as i18n.js translated it before.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "@vue/compiler-dom";
import { JSDOM } from "jsdom";

const VUE = "../lib/vue.esm-browser.prod.js";
const HEADER = "// Generated by `npm run build:map` from the #app element of index.html. Do not edit.\n";

/** The template of index.html's #app, with its translated text as t() calls. */
export function mapTemplate(indexHtml) {
  const doc = new JSDOM(indexHtml).window.document;
  const app = doc.getElementById("app");
  if (!app) throw new Error("index.html has no #app element");
  app.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = `{{ t('${el.getAttribute("data-i18n")}') }}`;
  });
  app.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    for (const pair of el.getAttribute("data-i18n-attr").split(";")) {
      const [attr, key] = pair.split(":").map((s) => s.trim());
      if (!attr || !key) continue;
      el.removeAttribute(attr);
      el.setAttribute(`:${attr}`, `t('${key}')`);
    }
  });
  return app.innerHTML;
}

/** The render function module for index.html. */
export function buildMapRender(indexHtml) {
  const { code } = compile(mapTemplate(indexHtml), { mode: "module", prefixIdentifiers: true, hoistStatic: true, cacheHandlers: true });
  return HEADER + code.replace(/ from "vue"/g, ` from "${VUE}"`) + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  writeFileSync(join(root, "src", "map-app.render.js"), buildMapRender(readFileSync(join(root, "index.html"), "utf8")));
  console.log("src/map-app.render.js written");
}
